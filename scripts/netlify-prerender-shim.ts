import { access, mkdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import type { Plugin } from "vite";

/**
 * Netlify-only prerender bridge.
 *
 * TanStack's prerender step boots `vite preview`, which imports dist/server/server.js.
 * @lovable.dev/vite-tanstack-config writes that file as a shim to nitro's `index.mjs`,
 * but nitro's netlify preset emits `.netlify/functions-internal/server/main.mjs`
 * (a Netlify function handler), so the Lovable shim is skipped and every page 500s.
 * This writes an equivalent shim to the Netlify handler after nitro builds and before
 * TanStack prerenders, then removes it so it is never published.
 */
const MARKER = "// Generated by scripts/netlify-prerender-shim.ts for the prerender preview server.";
const NETLIFY_ENTRY = ".netlify/functions-internal/server/main.mjs";
const SHIM_FILE = "dist/server/server.js";

function shimSource(specifier: string) {
  return `${MARKER}
import handler from "${specifier}";

export default {
  fetch(request) {
    // srvx's NodeRequest exposes \`ip\` as a getter-only accessor; the Netlify handler assigns to it.
    Object.defineProperty(request, "ip", { value: undefined, writable: true, configurable: true });
    return handler(request);
  },
};
`;
}

export function netlifyPrerenderShim(): Plugin[] {
  let root = process.cwd();
  let written: string | undefined;
  return [
    {
      name: "netlify-prerender-shim",
      apply: "build",
      configResolved(config) {
        root = config.root;
      },
      buildApp: {
        order: "post",
        async handler() {
          const entry = resolve(root, NETLIFY_ENTRY);
          try {
            await access(entry);
          } catch {
            console.warn(`[netlify-prerender-shim] ${NETLIFY_ENTRY} not found; prerender shim not written.`);
            return;
          }
          const target = resolve(root, SHIM_FILE);
          const occupant = await readFile(target, "utf8").catch(() => undefined);
          if (occupant !== undefined && !occupant.startsWith(MARKER)) return; // another shim already exists
          let specifier = relative(dirname(target), entry).split(sep).join("/");
          if (!specifier.startsWith(".")) specifier = `./${specifier}`;
          await mkdir(dirname(target), { recursive: true });
          await writeFile(target, shimSource(specifier));
          written = target;
        },
      },
    },
    {
      name: "netlify-prerender-shim-cleanup",
      apply: "build",
      enforce: "post",
      buildApp: {
        order: "post",
        async handler() {
          if (!written) return;
          await rm(written, { force: true });
          await rmdir(dirname(written)).catch(() => {}); // only removes it if now empty
          written = undefined;
        },
      },
    },
  ];
}
